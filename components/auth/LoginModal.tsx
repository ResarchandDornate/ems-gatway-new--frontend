"use client";

import { useState } from "react";
import { Lock, Loader2 } from "lucide-react";
import { login, activeSiteName, LoginError } from "@/lib/central";
import ApertureCarousel, { type Slide } from "@/components/ui/aperture-carousel";

/* Mirrors DEMO_LOGIN / DEMO_PASSWORD in lib/server/central/demo.ts (server-only). */
const DEMO_LOGIN = "customer";

const U = (id: string) =>
  "https://images.unsplash.com/photo-" + id + "?q=80&w=1800&auto=format&fit=crop";

/* The first slide is local, so it is on screen before any remote photo has
   loaded. The rest are stock photography. */
const SLIDES: Slide[] = [
  { image: "/unityess-solar-field.jpg", title: "UnityESS", caption: "Battery energy storage, monitored end to end.", alt: "UnityESS containers in a solar field" },
  { image: U("1613665813446-82a78c468a1d"), title: "Solar to Storage", caption: "Generated by day, stored for the evening peak." },
  { image: U("1509391366360-2e959784a276"), title: "Rooftop to Rack", caption: "Panels in the field, cells in the rack." },
  { image: U("1508514177221-188b1cf16e9d"), title: "Utility Scale", caption: "Every string, every cell, one dashboard." },
  { image: U("1473341304170-971dccb5ac1e"), title: "Grid Ready", caption: "Peak shaving and ToD savings, live." },
  { image: U("1466611653911-95081537e5b7"), title: "Clean Hours", caption: "Store the surplus, spend it when it counts." },
  { image: U("1497440001374-f26997328c1b"), title: "Every Panel", caption: "From the array to the battery, in one view." },
];

/**
 * Sign in to the Ornate Central EMS Backend.
 *
 * The field is an email now, not a username: the central backend authenticates
 * on `{ email, password }` and rejects a bare username with 422, not 401, so a
 * "customer"-style login fails as a malformed request rather than a wrong one.
 * The one exception is the demo account, `customer` / `customer`, which this
 * app's own server answers with a synthetic plant (lib/server/central/demo.ts)
 * — so the field is plain text, or the browser would refuse "customer".
 *
 * No "remember me". The UGX form had one because that client chose between
 * sessionStorage and localStorage; the central token carries its own expiry in
 * the JWT and is held until it
 * expires either way. A checkbox that changed nothing would be worse than no
 * checkbox.
 *
 * No `onSuccess` either — the session is an external store and the gate
 * subscribes to it, so a successful sign-in re-renders the gate on its own.
 * The callback this used to take was a second path to the same state, and the
 * two could disagree.
 */
export function LoginModal({ hero = true }: { hero?: boolean }) {
  const [username, setUsername] = useState("");
  const [password, setPassword] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault();
    await signIn(username, password);
  }

  /* The demo account (lib/server/central/demo.ts): fills the form so the
     credentials are visible, then signs in. */
  async function tryDemo() {
    setUsername(DEMO_LOGIN);
    setPassword(DEMO_LOGIN);
    await signIn(DEMO_LOGIN, DEMO_LOGIN);
  }

  async function signIn(email: string, pass: string) {
    setError(null);
    setLoading(true);
    try {
      await login(email, pass);
      /* Nothing to do on success. write() notified the store, the gate is
         subscribed, and this component is about to be unmounted by it. */
    } catch (err) {
      /* LoginError already carries a message written for the person reading
         it — auth.ts separates "that password was wrong" from "the site is not
         responding", which is the distinction that stops an operator retyping
         their password while a plant is offline. */
      setError(
        err instanceof LoginError || err instanceof Error
          ? err.message
          : "Sign-In Failed",
      );
    } finally {
      setLoading(false);
    }
  }

  const site = activeSiteName();

  const form = (
    <form onSubmit={handleSubmit} className="space-y-3">
      <div>
        <label className="filter-label">Email</label>
        <input
          type="text"
          inputMode="email"
          autoCapitalize="none"
          spellCheck={false}
          required
          value={username}
          onChange={(e) => setUsername(e.target.value)}
          className="filter-input"
          placeholder="you@ornatesolar.com"
          autoComplete="email"
          autoFocus
        />
      </div>
      <div>
        <label className="filter-label">Password</label>
        <input
          type="password"
          required
          value={password}
          onChange={(e) => setPassword(e.target.value)}
          className="filter-input"
          autoComplete="current-password"
        />
      </div>

      {error && (
        <div className="text-[12px] text-bad bg-bad/10 ring-1 ring-bad/30 rounded-md px-3 py-2 leading-relaxed">
          {error}
        </div>
      )}

      <button
        type="submit"
        disabled={loading || !username || !password}
        className="btn-primary w-full justify-center disabled:opacity-50 disabled:cursor-not-allowed"
      >
        {loading && <Loader2 size={13} className="animate-spin" />}
        {loading ? "Signing In…" : "Sign In"}
      </button>

      <p className="text-[11px] text-muted text-center pt-1">
        Just looking?{" "}
        <button
          type="button"
          onClick={tryDemo}
          disabled={loading}
          className="text-accent font-medium hover:underline disabled:opacity-50"
        >
          Try the demo
        </button>
        {" "}· <span className="font-mono">{DEMO_LOGIN}</span> / <span className="font-mono">{DEMO_LOGIN}</span>
      </p>
    </form>
  );

  /* The mobile app (/m) keeps the compact card: the carousel is the website's
     sign-in, and on a phone shell it would push the form below the fold. */
  if (!hero) {
    return (
      <div className="fixed inset-0 z-50 bg-bg/95 backdrop-blur-md grid place-items-center px-5">
        <div className="w-full max-w-[400px] surface-card p-6">
          <div className="flex items-center gap-3 mb-5">
            <div className="w-10 h-10 rounded-ctl bg-accent/12 ring-1 ring-accent/30 grid place-items-center">
              <Lock size={16} className="text-accent" />
            </div>
            <div>
              <h1 className="text-[15px] font-semibold text-ink leading-tight">
                UnityESS Sign In
              </h1>
              <div className="text-[11px] text-muted">
                {site || "UnityESS Central EMS"}
              </div>
            </div>
          </div>
          {form}
        </div>
      </div>
    );
  }

  return (
    <div className="fixed inset-0 z-50 bg-bg flex flex-col lg:grid lg:grid-cols-[minmax(0,1.3fr)_minmax(420px,1fr)] overflow-y-auto">
      <ApertureCarousel
        slides={SLIDES}
        height="100%"
        autoplay={6500}
        ariaLabel="UnityESS"
        className="shrink-0 !h-[34svh] lg:!h-full"
      />

      <div className="flex-1 grid place-items-center px-5 py-10 sm:px-10">
        <div className="w-full max-w-[380px]">
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src="/brand/unityess-logo.png" alt="UnityESS" width={176} height={24} className="brand-light h-6 w-auto mb-10" />
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src="/brand/unityess-logo-dark.png" alt="UnityESS" width={176} height={24} className="brand-dark h-6 w-auto mb-10" />

          <h1 className="text-[22px] font-semibold text-ink leading-tight">Sign In</h1>
          <p className="text-[12px] text-muted mt-1 mb-6">
            {site || "UnityESS Central EMS"}
          </p>

          {form}

          <p className="text-[11px] text-muted mt-10">© Ornate Solar · UnityESS</p>
        </div>
      </div>
    </div>
  );
}
